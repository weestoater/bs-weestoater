async function migrateArticles() {
  console.log("🔄 Starting articles migration...");
  console.log(`📊 Migrating ${articles.length} articles to Supabase\n`);

  try {
    // Check if articles already exist
    const { data: existingArticles } = await supabase
      .from("articles")
      .select("id");

    if (existingArticles && existingArticles.length > 0) {
      console.log(
        `⚠️  Found ${existingArticles.length} existing articles in database`,
      );
      console.log("   This migration will skip existing articles\n");
    }

    // Insert articles one by one with progress reporting
    let successCount = 0;
    let skipCount = 0;
    let errorCount = 0;

    for (const article of articles) {
      try {
        const { data, error } = await supabase
          .from("articles")
          .insert([article])
          .select();

        if (error) {
          if (error.code === "23505") {
            // Duplicate key
            console.log(`⏭️  Skipped: ${article.title} (already exists)`);
            skipCount++;
          } else {
            throw error;
          }
        } else {
          console.log(`✅ Migrated: ${article.title}`);
          successCount++;
        }
      } catch (err) {
        console.error(`❌ Error migrating ${article.title}:`, err.message);
        errorCount++;
      }
    }

    console.log("\n" + "=".repeat(60));
    console.log("Migration Summary:");
    console.log("=".repeat(60));
    console.log(`✅ Successfully migrated: ${successCount} articles`);
    console.log(`⏭️  Skipped (existing): ${skipCount} articles`);
    console.log(`❌ Errors: ${errorCount} articles`);
    console.log(`📊 Total processed: ${articles.length} articles`);
    console.log("=".repeat(60));

    if (successCount > 0) {
      console.log("\n🎉 Articles successfully migrated to Supabase!");
      console.log(
        "   You can now view them at: https://supabase.com/dashboard\n",
      );
    }
  } catch (error) {
    console.error("\n❌ Migration failed:", error);
    process.exit(1);
  }
}

// Run migration
migrateArticles();
